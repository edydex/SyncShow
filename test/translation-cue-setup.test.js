test('a real reopened Show package starts translation using its pinned full project, not its handoff summary or a newer draft', async t => {
  const directory = await fs.mkdtemp(path.join(os.tmpdir(),'translation-project-binding-'));
  t.after(()=>fs.rm(directory,{recursive:true,force:true}));
  const store = new ServiceProjectStore({rootPath:path.join(directory,'projects'),clock:()=>new Date('2026-10-25T12:00:00.000Z')});
  const created = await store.create({id:'sunday',title:'Sunday',serviceDate:'2026-10-25',profileId:'church'});
  let project = addProjectItem(created.project,{id:'opening',kind:'notice',title:'Welcome',textByChannel:{primary:'Welcome'}});
  project = addProjectItem(project,{id:'translation',kind:'notice',title:'Sermon',textByChannel:{primary:'Sermon'},translationCues:{self:'start'}});
  project = addProjectItem(project,{id:'closing',kind:'notice',title:'Closing',textByChannel:{primary:'Closing'},translationCues:{self:'stop'}});
  const saved = await store.save(project,{expectedRevisionId:created.revisionId});
  const publisher = new ShowPackagePublisher({projectStore:store,rootPath:path.join(directory,'packages'),fontPath:path.resolve(__dirname,'../assets/fonts/NotoSans-Variable.ttf')});
  const published = await publisher.publish({projectId:'sunday',revisionId:saved.revisionId,roleMapping:{english:'primary'},width:640,height:360,thumbnailWidth:100});
  const reopened = await publisher.open(published.manifest.id);
  const presentation = reopened.presentations.english;
  assert.equal(presentation.serviceHandoff.project.kind,undefined,'the actual Show handoff carries metadata only');
  const binding = {serverId:'church',syncId:'sunday',documentRevision:'c'.repeat(64),localRevisionId:'a'.repeat(64)};
  const result = await resolveCueBinding(presentation,binding,{serverId:'church'},store);
  assert.equal(result.serviceId, 'sunday');
  assert.equal(result.serviceRevision,heritageServiceDocumentRevision(createHeritageServiceDocument(saved.project)));
  const newer = await store.save({...saved.project,title:'A newer draft'},{expectedRevisionId:saved.revisionId});
  assert.notEqual(heritageServiceDocumentRevision(createHeritageServiceDocument(newer.project)),result.serviceRevision);
  assert.deepEqual(await resolveCueBinding(presentation,binding,{serverId:'church'},new ServiceProjectStore({rootPath:path.join(directory,'projects')})),result);
  const sent=[];
  const controller=new SlideTranslationCues({resolve:p=>resolveCueBinding(p,binding,{serverId:'church'},store),send:async command=>sent.push(command),changed(){}});
  await controller.navigate(presentation,0);
  await controller.navigate(presentation,1);
  await controller.navigate(presentation,2);
  assert.deepEqual(sent.map(command=>command.phase),['prepare','live','idle']);
  assert.ok(sent.every(command=>command.serviceRevision===result.serviceRevision));
});
test('saved layouts and late captions cannot paint outside the Show cue region', () => {
  const cues = [{id:'opening'}, {id:'before'}, {id:'start',translationAction:'start'}, {id:'sermon'}, {id:'stop',translationAction:'stop'}, {id:'song'}];
  const projection = new TranslationProjection();
  const settings = {language:'ru',layout:'lower-third',fontScale:1.25};
  projection.configure('english', settings);
  projection.accept({type:'public-state',state:{active:true,sessionId:'service',serverTimeUnixMs:Date.now(),languages:[{language:'ru',available:true}]}});
  projection.accept({type:'transcript',segment:{sessionId:'service',channelId:'ru',language:'ru',sequence:1,final:true,text:'Late caption'}});
  const frame = projection.frame('english');
  for (const index of [0, 1, 4, 5, 0]) {
    const scoped = cueScopedFrame(frame,{showActive:true,manual:false,cues,index});
    assert.equal(scoped.layout,'hidden');
    assert.equal(scoped.moving,false);
    assert.deepEqual(scoped.phrases,[]);
  }
  for (const index of [2, 3]) assert.equal(cueScopedFrame(frame,{showActive:true,cues,index}),frame);
  assert.deepEqual(projection.outputs.get('english'),settings,'cue visibility never overwrites the saved layout');
  assert.equal(cueScopedFrame(frame,{showActive:true,manual:true,cues,index:5}),frame,'Translate remains available outside the cue region');
  assert.equal(cueScopedFrame(frame,{showActive:false,cues,index:5}),frame,'standalone translation screens keep their selected layout');
});
test('a cue reveals its configured caption band even if saved defaults hide captions', () => {
  const output = {sourceRoleId:'english'};
  const saved = {language:'en',layout:'hidden',fontScale:1.25};
  const settings = {targetLanguage:'ru',captionStyle:'lower-third',captionChannel:'both'};
  assert.deepEqual(cueOutputSettings(output,{phase:'prepare',settings},{},saved),{language:'ru',layout:'hidden',fontScale:1.25});
  assert.deepEqual(cueOutputSettings(output,{phase:'live',settings},{},saved),{language:'ru',layout:'lower-third',fontScale:1.25});
  assert.equal(cueOutputSettings({...output,kind:'singer'},{phase:'live',settings},{},saved).layout,'hidden');
  assert.deepEqual(cueOutputSettings(output,{phase:'live',manual:true},{},saved),saved);
});
