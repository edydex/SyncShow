'use strict';
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const { spawnSync } = require('node:child_process');
const evidence = fs.mkdtempSync(path.join(os.tmpdir(), 'syncshow-teaching-'));
const profile = path.join(evidence, 'profile'); fs.mkdirSync(profile);
const env = { ...process.env, SYNCSHOW_TEACHING_EVIDENCE: evidence, SYNCSHOW_TEST_USER_DATA_DIR: profile };
delete env.ELECTRON_RUN_AS_NODE;
const result = spawnSync(require('electron'), [path.join(__dirname, 'fixtures/teaching-electron-app.js'), '--syncshow-test-user-data'], { env, stdio: 'inherit', timeout: 120000 });
if (result.error) throw result.error;
process.exit(result.status ?? 1);
